#!/usr/bin/env python3
"""Writes Sources/BekitzurVocabulary/BuiltInVocabulary.swift from eval/vocabulary/built-in.txt.

The app can't ship the text file as a SwiftPM resource (the resource bundle would sit at the root of the .app, which
breaks its signature), so the terms are compiled in. Run this after editing built-in.txt.
"""

import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
terms = [t.strip() for t in (root / "eval/vocabulary/built-in.txt").read_text(encoding="utf-8").splitlines() if t.strip()]
lines = ",\n".join(f"        {json.dumps(t)}" for t in terms)
(root / "Sources/BekitzurVocabulary/BuiltInVocabulary.swift").write_text(
    "// Generated by scripts/generate-built-in-vocabulary.py from eval/vocabulary/built-in.txt; edit that file instead.\n\n"
    "enum BuiltInVocabulary {\n"
    "    /// Common English tech terms that Israeli teams say inside Hebrew sentences.\n"
    f"    static let terms: [String] = [\n{lines},\n    ]\n"
    "}\n",
    encoding="utf-8",
)
print(f"{len(terms)} terms")
